#!/usr/bin/env python3
"""DELTA HAProxy setup: Ubuntu 24.04 amd64, Iran-only, over RCLocalL GRE."""
import hashlib
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import tempfile
from datetime import datetime

DEFAULT_PORTS = (443, 80, 8880, 2052, 2082, 2095, 2086, 1370, 1372,
                 15156, 8443, 12321, 1379, 11231, 8080)
BEGIN = '# BEGIN DELTA MANAGED HAPROXY'
END = '# END DELTA MANAGED HAPROXY'
CONFIG = Path('/etc/haproxy/haproxy.cfg')
REPO = 'https://raw.githubusercontent.com/deltashopsiavash/rclocall/main/packages/'
PACKAGES = (
    ('liblua5.4-0_5.4.6-3build2_amd64.deb',
     '6a520259e5b06e86191a25af6d448387cdd2b3d291a0aa956ce272e84d071260',
     'https://eu.edge.kernel.org/ubuntu/ubuntu/pool/main/l/lua5.4/'),
    ('haproxy_2.8.16-0ubuntu0.24.04.2_amd64.deb',
     '05df8fef3a26e6535cfe579b0c99c3196e7d9e3390d9be707991d44ab75ffcd6',
     'https://mirror-prg.webglobe.com/ubuntu/ubuntu/pool/main/h/haproxy/'),
)
SECTION = re.compile(r'^\s*(global|defaults|frontend|backend|listen|peers|resolvers|'
                     r'mailers|cache|ring|program|fcgi-app)\s+(\S+)?', re.I)
OLD_FRONT = re.compile(r'^inbound-\d+$')
OLD_BACK = re.compile(r'^inbound-\d+-backend$')


def run(*args, check=True, **kwargs):
    return subprocess.run(args, check=check, text=True, **kwargs)


def parse_ports(value):
    """Support 443,2083,8282 and spaces; blank means DELTA defaults."""
    if not value.strip():
        return list(DEFAULT_PORTS)
    items = value.split(',')
    if not 1 <= len(items) <= 64:
        raise ValueError('Enter 1 to 64 TCP ports.')
    ports = []
    for item in items:
        if not re.fullmatch(r'\s*\d{1,5}\s*', item):
            raise ValueError('Enter comma-separated TCP ports (example: 443,2083,8282).')
        port = int(item)
        if not 1 <= port <= 65535:
            raise ValueError('TCP ports must be between 1 and 65535.')
        if port in ports:
            raise ValueError(f'Duplicate TCP port: {port}')
        ports.append(port)
    return ports


def make_block(ports, foreign_gre):
    """Use the FOREIGN tunnel address as backend, never Iran's local GRE IP."""
    lines = [BEGIN, '# Generated by DELTA; edit using menu 4.', '']
    for port in ports:
        lines += [
            f'frontend inbound-{port}',
            f'        bind *:{port}',
            '        mode tcp',
            f'        default_backend inbound-{port}-backend',
            '',
            f'backend inbound-{port}-backend',
            '        balance roundrobin',
            '        mode tcp',
            f'        server web{port} {foreign_gre}:{port} check',
            '',
        ]
    lines.append(END)
    return '\n'.join(lines) + '\n'


def filter_existing_config(config_text):
    """Keep all unrelated HAProxy sections, remove only DELTA/legacy inbound blocks."""
    text = config_text
    if text.count(BEGIN) != text.count(END):
        raise ValueError('Broken DELTA markers in HAProxy config; refusing to modify.')
    if text.count(BEGIN) > 1:
        raise ValueError('Multiple DELTA config blocks found; refusing to modify.')
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        text = text[:a] + text[b:]
    sections = []
    current = []
    count = 0
    for line in text.splitlines(keepends=True):
        match = SECTION.match(line)
        if match:
            if current:
                sections.append(current)
            current = [line]
        else:
            current.append(line)
    if current:
        sections.append(current)

    remaining = []
    for sec in sections:
        header = SECTION.match(sec[0])
        name = (header.group(2) or '') if header else ''
        kind = header.group(1).lower() if header else ''
        if (kind == 'frontend' and OLD_FRONT.fullmatch(name)
                or kind == 'backend' and OLD_BACK.fullmatch(name)):
            count += 1
            continue
        remaining.extend(sec)
    return ''.join(remaining).rstrip() + '\n', count


def detect_unmanaged_conflicts(text, ports):
    """Reject wildcard binds to requested ports in unrelated HAProxy sections."""
    for line in text.splitlines():
        match = re.match(r'^\s*bind\s+(?:\*|0\.0\.0\.0|\[::\]):(\d+)(?:\s|$)', line)
        if match and int(match.group(1)) in ports:
            raise ValueError(f'Port {match.group(1)} is already used by another HAProxy section.')


def fallback_config():
    return ('global\n'
            '    log /dev/log local0\n'
            '    daemon\n'
            '    maxconn 2048\n\n'
            'defaults\n'
            '    log global\n'
            '    mode tcp\n'
            '    option tcplog\n'
            '    timeout connect 10s\n'
            '    timeout client 1h\n'
            '    timeout server 1h\n\n')


def check_ubuntu_amd64():
    if platform.machine() not in ('x86_64', 'amd64'):
        raise RuntimeError('These DEB files require x86_64/amd64.')
    release = Path('/etc/os-release').read_text()
    if not re.search(r'^ID=ubuntu\s*$', release, re.M) or not re.search(
            r'^VERSION_ID="?24\.04"?\s*$', release, re.M):
        raise RuntimeError('Uploaded DEB packages are specifically for Ubuntu 24.04 amd64.')


def sha256(path):
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def fetch_package(file_name, expected_sha, fallback_url, destination):
    sources = (REPO + file_name, fallback_url + file_name)
    for source in sources:
        if destination.exists():
            destination.unlink()
        attempt = run('curl', '-fLSs', '--retry', '2', '--connect-timeout',
                      '15', '--max-time', '120', source, '-o', str(destination),
                      check=False, capture_output=True)
        if attempt.returncode != 0:
            continue
        if sha256(destination) != expected_sha:
            destination.unlink(missing_ok=True)
            raise RuntimeError(f'SHA256 mismatch downloading {file_name} from {source}')
        pkg = run('dpkg-deb', '-f', str(destination), 'Architecture',
                  capture_output=True)
        if pkg.stdout.strip() != 'amd64':
            raise RuntimeError(f'Wrong architecture for {file_name}.')
        print(f'  [OK] Verified package: {file_name}')
        return
    raise RuntimeError(f'Unable to download {file_name} from GitHub or Ubuntu mirror.')


def install_packages():
    if shutil.which('haproxy'):
        print('  [OK] HAProxy is already installed; keeping existing version.')
        return
    check_ubuntu_amd64()
    with tempfile.TemporaryDirectory(prefix='delta-haproxy-') as directory:
        local_files = []
        for filename, checksum, mirror in PACKAGES:
            destination = Path(directory) / filename
            print('  Downloading:', filename)
            fetch_package(filename, checksum, mirror, destination)
            local_files.append(str(destination))
        # Installs the supplied exact DEBs, with dependency handling.
        run('apt-get', 'install', '-y', '--no-install-recommends', *local_files)


def persist_config(ports, foreign_gre):
    original = CONFIG.read_text() if CONFIG.exists() else ''
    base, replaced = filter_existing_config(original)
    if replaced:
        print(f'  Found {replaced} existing inbound section(s).')
        answer = input('  Replace those inbound sections? [y/N]: ').strip().lower()
        if answer not in ('y', 'yes'):
            print('  Cancelled: existing HAProxy config unchanged.')
            return False
    if not base.strip():
        base = fallback_config()
    detect_unmanaged_conflicts(base, ports)
    proposed = base.rstrip() + '\n\n' + make_block(ports, foreign_gre)

    # Test candidate BEFORE touching live config.
    CONFIG.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', prefix='.delta-check-', suffix='.cfg',
                                     dir=CONFIG.parent, delete=False) as file:
        file.write(proposed)
        staging = Path(file.name)
    try:
        run('haproxy', '-c', '-f', str(staging))
        if CONFIG.exists():
            backup = CONFIG.with_name('haproxy.cfg.delta-backup-' +
                                      datetime.now().strftime('%Y%m%d-%H%M%S-%f'))
            shutil.copy2(CONFIG, backup)
            print('  [OK] Backup:', backup)
        else:
            backup = None
        # Atomic swap. Keep existing on rollback.
        os.chmod(staging, 0o644)
        os.replace(staging, CONFIG)
        staging = None
        try:
            run('service', 'haproxy', 'restart')
            run('systemctl', 'enable', 'haproxy')
        except subprocess.CalledProcessError:
            if backup:
                shutil.copy2(backup, CONFIG)
            else:
                CONFIG.unlink(missing_ok=True)
            run('service', 'haproxy', 'restart', check=False)
            raise RuntimeError('HAProxy restart failed; previous configuration restored.')
        print('  [OK] HAProxy restarted successfully.')
        return True
    finally:
        if staging is not None:
            staging.unlink(missing_ok=True)


def setup(gre_data, address_fn):
    """Called by the DELTA manager, with its saved role and address function."""
    print('\n  ========== Install HAProxy (Iran only) ==========')
    if gre_data is None or gre_data.get('role') != 'iran':
        print('  [ERROR] HAProxy installation is available on IRAN servers only.')
        print('  Install the GRE tunnel on this Iran server first.')
        return
    links = gre_data['links']
    if not links:
        print('  [ERROR] No configured GRE links were found.')
        return

    print('  Available FOREIGN GRE peers:')
    for link in sorted(links, key=lambda link: link['id']):
        iran_local, foreign_local = address_fn(link['id'], 'iran')
        print(f"    Link {link['id']} | Foreign IPv4 {link['peer_public']}")
        print(f'      Iran GRE {iran_local} -> Foreign GRE {foreign_local}')
    if len(links) == 1:
        selected = links[0]
    else:
        while True:
            answer = input('  Select Link ID for HAProxy backend: ').strip()
            chosen = next((l for l in links if str(l['id']) == answer), None)
            if chosen is not None:
                selected = chosen
                break
            print('  [WARN] Enter one of the Link IDs above.')
    iran_local, foreign_local = address_fn(selected['id'], 'iran')
    if iran_local == foreign_local:
        raise ValueError('Iran and Foreign local GRE IP must differ.')
    print(f'  Selected FOREIGN local IP: {foreign_local}')
    print(f'  This is the HAProxy backend IP, NOT Iran local {iran_local}.')
    print('\n  Default TCP ports:')
    print('  ' + ','.join(map(str, DEFAULT_PORTS[:8])))
    print('  ' + ','.join(map(str, DEFAULT_PORTS[8:])))
    while True:
        response = input('  Custom ports (e.g. 443,2083,8282; Enter = defaults): ')
        try:
            ports = parse_ports(response)
            break
        except ValueError as exc:
            print('  [WARN]', exc)
    print(f'\n  Backend = {foreign_local}')
    print('  Ports   =', ','.join(map(str, ports)))
    print('  Mode    = TCP, same inbound and backend ports')
    if input('  Install/Update HAProxy now? [y/N]: ').strip().lower() not in ('y', 'yes'):
        print('  Cancelled.')
        return
    install_packages()
    if persist_config(ports, foreign_local):
        print(f'  [OK] {len(ports)} TCP port(s) routed to {foreign_local}')
        print('  Note: the Foreign server must listen on those TCP ports.')
